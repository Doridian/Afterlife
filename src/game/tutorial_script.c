/*
 * The lesson scripts of the tutorial (ALIFE.EXE 0x41f611 tutorial_script,
 * the switch on the lesson number after the common prologue): one op per
 * call of the original, in order, with the original's guards around the
 * speeches (TO_IF .. TO_ENDIF: skipped once the speech was silenced, i.e.
 * the lesson was stopped). Operations are described in game/tutorial.h.
 *
 * Only addresses are here: the subtitles are ALIFE.EXE texts looked up by
 * their virtual addresses (data compiled in from src/data), the voices are
 * resources of the bundles (sound slot 199).
 */
